          SUM(quantity) AS total_quantity
    FROM retail_sales
    GROUP BY category
    ORDER BY total_quantity DESC;

  --Average price per unit by category.
    SELECT 
        category, 
        AVG(price_per_unit) AS avg_price
     FROM retail_sales
     GROUP BY category;

--ANOMOLY DETECTION
 --Identify transactions with unusually high or low total sales.
  SELECT *
     FROM retail_sales
     WHERE total_sale > (SELECT AVG(total_sale) + 3 * STDEV(total_sale) FROM retail_sales)
     OR total_sale < (SELECT AVG(total_sale) - 3 * STDEV(total_sale) FROM retail_sales);

 --Check for transactions where COGS is higher than total sales.
  SELECT *
    FROM retail_sales
    WHERE cogs > total_sale;

--Analyze sales trends over time using SQL window functions:
  SELECT 
    sale_date, 
    SUM(total_sale) AS daily_sales,
    AVG(SUM(total_sale)) OVER (ORDER BY sale_date ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS rolling_avg_7_days
   FROM retail_sales
   GROUP BY sale_date
   ORDER BY sale_date;

